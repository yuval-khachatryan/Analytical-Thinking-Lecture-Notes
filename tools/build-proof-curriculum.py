"""Build rule-availability positions from source order, without editing exercises."""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[1]
positions, sources, pages, duplicates = {}, {}, {}, set()
for chapter, name in enumerate(("01-Introduction.qmd", "02-Sequences.qmd"), 1):
    page = name.replace(".qmd", ".html")
    pages[page] = {}
    for line, text in enumerate((ROOT / name).read_text().splitlines(), 1):
        # Explicit stable IDs on headings, divs and spans; ignore reference links.
        for identifier in re.findall(r"\{[^}\n]*?#([\w-]+)(?=[\s}])", text):
            if identifier in pages[page]:
                raise ValueError(f"Duplicate course ID in {page}: {identifier}")
            if identifier in positions:
                duplicates.add(identifier)
            positions[identifier] = chapter * 100000 + line
            pages[page][identifier] = positions[identifier]
            sources[identifier] = page
for identifier in duplicates:
    del positions[identifier]
    del sources[identifier]
data = {"version": 1, "positions": positions, "sources": sources, "pages": pages}
output = ROOT / "assets/proof-curriculum.js"
output.write_text("// Generated by tools/build-proof-curriculum.py; source order, not printed numbering.\n"
                  "(function(root){root.CourseProofCurriculum=" + json.dumps(data, ensure_ascii=False, separators=(",", ":"))
                  + ";})(typeof globalThis!=='undefined'?globalThis:this);\n")
print(f"Proof curriculum: {len(positions)} stable source positions.")
